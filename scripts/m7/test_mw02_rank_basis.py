"""MW-02 tests; deliberately run in the pinned Sage environment.

This file is added before the implementation.  It is a test-only harness and
does not produce a family theorem or modify the campaign helper.
"""

from __future__ import annotations

import json
import sys

from sage.all import EllipticCurve, QQ

from mw02_rank_basis import (
    IndependenceUnresolved,
    RankContradiction,
    SaturationUnresolved,
    independence_witness,
    select_independent_subset,
    validate_saturation_result,
    full_saturate_basis,
)


E19 = EllipticCurve([0, 7240, 0, 7240 * 381, 7240 * 381**2])
P = E19([-3666, 197412])
Q = E19([-46, 30648])
WITNESS_BOUND = 50


def expect_unresolved(action):
    try:
        action()
    except IndependenceUnresolved as error:
        assert "INDEPENDENCE_UNRESOLVED" in str(error)
        return
    raise AssertionError("dependent or empty pool was accepted as independent")


def run() -> dict:
    # No candidate point is not evidence of rank zero or dependence.
    expect_unresolved(lambda: select_independent_subset(E19, [], 1, prime_bound=WITNESS_BOUND))

    # An expanded rank-one pool is legal.  Opposites and multiples must not be
    # truncated or treated as a false basis merely because the pool is larger.
    chosen, witness = select_independent_subset(
        E19, [P, -P, 2 * P], 1, prime_bound=WITNESS_BOUND
    )
    assert len(chosen) == 1
    assert witness["rank"] == 1

    # A rank-two pool containing only a subgroup chain is unresolved, not rank
    # one and not a certified basis.
    expect_unresolved(
        lambda: select_independent_subset(E19, [P, 2 * P], 2, prime_bound=WITNESS_BOUND)
    )

    # The rank-two pool may contain dependent extras; a verified pair is enough
    # to continue, while the complete pool remains retained as input data.
    chosen, witness = select_independent_subset(
        E19, [P, Q, P + Q, -P], 2, prime_bound=WITNESS_BOUND
    )
    assert len(chosen) == 2
    assert witness["rank"] == 2

    # If the pool itself contains a witnessed subgroup of rank above PARI's
    # upper bound, that is a contradiction, never a reason to clamp the rank.
    try:
        select_independent_subset(E19, [P, Q], 1, prime_bound=WITNESS_BOUND)
    except RankContradiction as error:
        assert "RANK_CONTRADICTION" in str(error)
    else:
        raise AssertionError("rank-above-bound pool was silently clamped")

    # The known rank-zero torsion fixture is valid point data but cannot supply
    # positive-rank evidence.
    torsion_curve = EllipticCurve([0, -1, 1, -10, -20])
    torsion_point = torsion_curve([5, 5])
    expect_unresolved(
        lambda: select_independent_subset(
            torsion_curve, [torsion_point], 1, prime_bound=WITNESS_BOUND
        )
    )

    # The doubled rank-two subgroup intentionally fails at ell=2 but succeeds
    # at ell=3.  A first failed search is therefore not a dependence result.
    doubled = independence_witness(
        E19, [2 * P, 2 * Q], 2, prime_bound=WITNESS_BOUND
    )
    assert doubled["ell"] == 3
    assert any(attempt["ell"] == 2 and attempt["status"] == "unresolved"
               for attempt in doubled["attempts"])
    assert doubled["direct_group_counts_verified"] is True

    # A doubled known N=11 generator must be enlarged by all-prime saturation;
    # index one or the input point alone is not an acceptable result.
    e11 = EllipticCurve([0, 1464, 0, 194712, 25896696])
    g11 = e11([QQ(-8330) / 9, QQ(473032) / 27])
    saturated, saturation = full_saturate_basis(
        e11, [2 * g11], 1, prime_bound=WITNESS_BOUND
    )
    assert saturation["index"] > 1
    assert len(saturated) == 1
    assert saturation["output_independence"]["rank"] == 1

    # The rank-two fixture exercises the same returned-basis requirement and
    # the expected enlargement of the subgroup generated by [2P, 2Q].
    saturated_two, saturation_two = full_saturate_basis(
        E19, [2 * P, 2 * Q], 2, prime_bound=WITNESS_BOUND
    )
    assert saturation_two["index"] > 1
    assert len(saturated_two) == 2
    assert saturation_two["output_independence"]["rank"] == 2

    # Malformed or unresolved backend output is a closed failure, not an empty
    # basis or a successful saturation claim.
    for value in ((True, 1, "[2]"), (True, 1, "unknown"), (False, 1, "[ ]")):
        try:
            validate_saturation_result(value)
        except (SaturationUnresolved, ValueError):
            pass
        else:
            raise AssertionError("invalid saturation result was accepted")

    return {
        "ok": True,
        "tests": 10,
        "status": "PASSED",
        "warning": "MW-02 qualification evidence; not a family theorem",
    }


def main() -> None:
    record = run()
    json.dump(record, sys.stdout, sort_keys=True, separators=(",", ":"))
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
